@Composable
private fun LockifyApp(vault: SecureVault, activity: FragmentActivity) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    var configured by remember { mutableStateOf(vault.configured()) }
    var unlocked by remember { mutableStateOf(false) }
    var pin by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var message by remember { mutableStateOf("") }
    var logins by remember { mutableStateOf(emptyList<LoginEntry>()) }
    var search by remember { mutableStateOf("") }
    var categoryFilter by remember { mutableStateOf("All") }
    var editing by remember { mutableStateOf<LoginEntry?>(null) }
    var adding by remember { mutableStateOf(false) }
    var showGenerator by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf("") }
    var generatorLength by remember { mutableIntStateOf(20) }
    var includeSymbols by remember { mutableStateOf(true) }
    var showSettings by remember { mutableStateOf(false) }
    var backupPass by remember { mutableStateOf("") }
    var backupMode by remember { mutableStateOf("export") }
    var externalPickerActive by remember { mutableStateOf(false) }
    val scope = rememberCoroutineScope()

    fun refresh() { logins = vault.entries() }
    fun lockNow() { vault.lock(); logins = emptyList(); unlocked = false; pin = ""; confirm = "" }

    // Lock immediately when the app leaves the foreground; no vault key is kept in background.
    DisposableEffect(lifecycleOwner, unlocked) {
        val observer = LifecycleEventObserver { _, event ->
            if (event == Lifecycle.Event.ON_STOP && unlocked && !externalPickerActive) lockNow()
        }
        lifecycleOwner.lifecycle.addObserver(observer)
        onDispose { lifecycleOwner.lifecycle.removeObserver(observer) }
    }

    val createBackup = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("application/octet-stream")) { uri ->
        if (uri != null) scope.launch {
            try {
                val pass = backupPass.toCharArray()
                val bytes = withContext(Dispatchers.IO) { try { vault.exportBackup(pass) } finally { pass.fill('\u0000') } }
                withContext(Dispatchers.IO) { context.contentResolver.openOutputStream(uri)?.use { it.write(bytes) } ?: error("Cannot write file") }
                message = "Encrypted backup saved. Keep its passphrase safe."
            } catch (e: Exception) { message = "Backup failed: ${e.message}" }
            backupPass = ""
        }
    }
    val openBackup = rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
        if (uri != null) scope.launch {
            try {
                val bytes = withContext(Dispatchers.IO) { context.contentResolver.openInputStream(uri)?.use { it.readBytes() } ?: error("Cannot read file") }
                val pass = backupPass.toCharArray()
                withContext(Dispatchers.IO) { try { vault.importBackup(bytes, pass, false) } finally { pass.fill('\u0000'); bytes.fill(0) } }
                refresh()
                message = "Backup imported and merged."
            } catch (e: Exception) { message = "Import failed. Check passphrase and file." }
            backupPass = ""
        }
    }

    fun biometricPrompt(cipher: Cipher, encrypting: Boolean) {
        val executor = ContextCompat.getMainExecutor(context)
        val prompt = BiometricPrompt(activity, executor, object : BiometricPrompt.AuthenticationCallback() {
            override fun onAuthenticationSucceeded(result: BiometricPrompt.AuthenticationResult) {
                try {
                    val authenticatedCipher = result.cryptoObject?.cipher ?: error("Biometric cipher unavailable")
                    if (encrypting) vault.finishBiometricEnrollment(authenticatedCipher)
                    else { vault.finishBiometricUnlock(authenticatedCipher); refresh(); unlocked = true }
                    message = if (encrypting) "Fingerprint unlock enabled." else ""
                } catch (e: Exception) { message = "Fingerprint operation failed. Unlock with PIN." }
            }
            override fun onAuthenticationError(errorCode: Int, errString: CharSequence) { message = errString.toString() }
            override fun onAuthenticationFailed() { message = "Fingerprint not recognized." }
        })
        prompt.authenticate(
            BiometricPrompt.PromptInfo.Builder()
                .setTitle(if (encrypting) "Enable fingerprint unlock" else "Unlock Lockify")
                .setSubtitle("Authenticate to protect your vault key")
                .setNegativeButtonText("Cancel")
                .build(),
            BiometricPrompt.CryptoObject(cipher)
        )
    }

    MaterialTheme(colorScheme = darkColorScheme(background = Ink, surface = Panel, primary = Accent, onSurface = Color.White)) {
        Surface(Modifier.fillMaxSize(), color = Ink) {
            if (!unlocked) {
                Column(Modifier.fillMaxSize().padding(24.dp), horizontalAlignment = Alignment.CenterHorizontally, verticalArrangement = Arrangement.Center) {
                    AnimatedLockifyRobot(Modifier.size(116.dp))
                    Text("LOCKIFY", fontSize = 28.sp, fontWeight = FontWeight.Bold, letterSpacing = 3.sp)
                    Text(if (configured) "Unlock your private vault" else "Create your private vault", color = Muted)
                    Spacer(Modifier.height(24.dp))
                    OutlinedTextField(pin, { if (it.length <= 12 && it.all(Char::isDigit)) pin = it }, label = { Text("6–12 digit PIN") }, singleLine = true, visualTransformation = PasswordVisualTransformation(), modifier = Modifier.fillMaxWidth())
                    if (!configured) OutlinedTextField(confirm, { if (it.length <= 12 && it.all(Char::isDigit)) confirm = it }, label = { Text("Confirm PIN") }, singleLine = true, visualTransformation = PasswordVisualTransformation(), modifier = Modifier.fillMaxWidth())
                    if (message.isNotBlank()) Text(message, color = Color(0xFFFF8A8A))
                    Spacer(Modifier.height(12.dp))
                    Button(onClick = {
                        if (pin.length < 6) message = "PIN must be at least 6 digits."
                        else if (!configured && pin != confirm) message = "PINs do not match."
                        else {
                            val chars = pin.toCharArray()
                            scope.launch {
                                try {
                                    withContext(Dispatchers.IO) { if (configured) vault.unlock(chars) else vault.create(chars) }
                                    configured = true; refresh(); unlocked = true; message = ""
                                } catch (e: Exception) { message = e.message?.substringAfter("LOCKOUT:")?.let { "Too many attempts. Wait before trying again." } ?: "Incorrect PIN or vault error." }
                                finally { chars.fill('\u0000'); pin = ""; confirm = "" }
                            }
                        }
                    }, modifier = Modifier.fillMaxWidth()) { Text(if (configured) "Unlock with PIN" else "Create vault") }
                    if (configured && vault.isBiometricEnabled()) {
                        OutlinedButton(onClick = {
                            try { biometricPrompt(vault.biometricDecryptCipher(), false) }
                            catch (_: Exception) { message = "Fingerprint unavailable. Use PIN." }
                        }, modifier = Modifier.fillMaxWidth()) { Text("Unlock with fingerprint") }
                    }
                    Text("PIN is not stored directly. There is no PIN recovery.", color = Muted, fontSize = 11.sp)
                }
            } else {
                Column(Modifier.fillMaxSize().padding(16.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Column(Modifier.weight(1f)) {
                            Row(verticalAlignment = Alignment.CenterVertically) { AnimatedLockifyRobot(Modifier.size(44.dp)); Spacer(Modifier.width(8.dp)); Text("LOCKIFY", color = Accent, fontWeight = FontWeight.Bold, letterSpacing = 2.sp) }
                            Text("Your encrypted vault", fontSize = 23.sp, fontWeight = FontWeight.Bold)
                        }
                        TextButton(onClick = { showSettings = true }) { Text("Settings") }
                        IconButton(onClick = { lockNow() }) { Icon(Icons.Default.Lock, "Lock now") }
                    }
                    Card(colors = CardDefaults.cardColors(containerColor = Panel)) {
                        Row(Modifier.fillMaxWidth().padding(16.dp), verticalAlignment = Alignment.CenterVertically) {
                            Column(Modifier.weight(1f)) { Text("SAVED LOGINS", color = Muted); Text("${logins.size}", fontSize = 28.sp, fontWeight = FontWeight.Bold) }
                            Icon(Icons.Default.Security, null, tint = Accent)
                        }
                    }
                    Spacer(Modifier.height(10.dp))
                    OutlinedTextField(search, { search = it }, modifier = Modifier.fillMaxWidth(), label = { Text("Search accounts") }, singleLine = true)
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text("Category", color = Muted)
                        Spacer(Modifier.width(8.dp))
                        var expanded by remember { mutableStateOf(false) }
                        Box {
                            TextButton(onClick = { expanded = true }) { Text(categoryFilter) }
                            DropdownMenu(expanded, { expanded = false }) {
                                (listOf("All") + logins.map { it.category }.distinct().sorted()).forEach { c ->
                                    DropdownMenuItem(text = { Text(c) }, onClick = { categoryFilter = c; expanded = false })
                                }
                            }
                        }
                        Spacer(Modifier.weight(1f))
                        FilledIconButton(onClick = { editing = null; adding = true }) { Icon(Icons.Default.Add, "Add login") }
                    }
                    val filtered = logins.filter {
                        (categoryFilter == "All" || it.category == categoryFilter) &&
                            (it.title.contains(search, true) || it.username.contains(search, true))
                    }
                    LazyColumn(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        items(filtered, key = { it.id }) { item ->
                            Card(colors = CardDefaults.cardColors(containerColor = Panel), shape = RoundedCornerShape(14.dp)) {
                                Column(Modifier.fillMaxWidth().padding(12.dp)) {
                                    var passwordVisible by remember(item.id) { mutableStateOf(false) }
                                    Text(item.title, fontWeight = FontWeight.SemiBold)
                                    Text("${item.username} • ${item.category}", color = Muted, fontSize = 12.sp)
                                    if (passwordVisible) Text("Password: ${item.password}", color = Accent)
                                    Row(verticalAlignment = Alignment.CenterVertically) {
                                        TextButton(onClick = { passwordVisible = !passwordVisible }) {
                                            Text(if (passwordVisible) "Hide password" else "Show password")
                                        }
                                        TextButton(onClick = {
                                            val clipboard = context.getSystemService(android.content.Context.CLIPBOARD_SERVICE) as android.content.ClipboardManager
                                            clipboard.setPrimaryClip(android.content.ClipData.newPlainText("Saved password", item.password))
                                            message = "Password copied to clipboard."
                                        }) { Text("Copy password") }
                                    }
                                    Row {
                                        TextButton(onClick = { editing = item; adding = true }) { Text("Edit") }
                                        TextButton(onClick = {
                                            val updated = logins.filterNot { it.id == item.id }
                                            scope.launch { withContext(Dispatchers.IO) { vault.save(updated) }; logins = updated }
                                        }) { Text("Delete", color = Color(0xFFFF8A8A)) }
                                    }
                                }
                            }
                        }
                    }
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        OutlinedButton(onClick = { showGenerator = true }, modifier = Modifier.weight(1f)) { Text("Password generator") }
                        OutlinedButton(onClick = { showSettings = true }, modifier = Modifier.weight(1f)) { Text("Backup / settings") }
                    }
                }
            }

            if (adding && unlocked) {
                var title by remember(editing) { mutableStateOf(editing?.title ?: "") }
                var username by remember(editing) { mutableStateOf(editing?.username ?: "") }
                var password by remember(editing) { mutableStateOf(editing?.password ?: "") }
                var category by remember(editing) { mutableStateOf(editing?.category ?: "Other") }
                AlertDialog(onDismissRequest = { adding = false; editing = null },
                    title = { Text(if (editing == null) "Add login" else "Edit login") },
                    text = { Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        OutlinedTextField(title, { title = it }, label = { Text("Website / app") }, singleLine = true)
                        OutlinedTextField(username, { username = it }, label = { Text("Username / email") }, singleLine = true)
                        OutlinedTextField(password, { password = it }, label = { Text("Password") }, singleLine = true, visualTransformation = PasswordVisualTransformation())
                        OutlinedTextField(category, { category = it }, label = { Text("Category (e.g. Social, Work)") }, singleLine = true)
                    } },
                    confirmButton = { TextButton(onClick = {
                        if (title.isNotBlank() && username.isNotBlank() && password.isNotBlank()) {
                            val item = LoginEntry(editing?.id ?: UUID.randomUUID().toString(), title.trim(), username.trim(), password, category.trim().ifBlank { "Other" })
                            val updated = if (editing == null) logins + item else logins.map { if (it.id == item.id) item else it }
                            scope.launch {
                                try { withContext(Dispatchers.IO) { vault.save(updated) }; logins = updated; adding = false; editing = null }
                                catch (_: Exception) { message = "Could not save login." }
                            }
                        }
                    }) { Text("Save encrypted") } },
                    dismissButton = { TextButton(onClick = { adding = false; editing = null }) { Text("Cancel") } })
            }

            if (showGenerator) AlertDialog(onDismissRequest = { showGenerator = false },
                title = { Text("Password generator") },
                text = { Column {
                    Text("Length: $generatorLength")
                    Slider(value = generatorLength.toFloat(), onValueChange = { generatorLength = it.toInt() }, valueRange = 8f..64f, steps = 55)
                    Row(verticalAlignment = Alignment.CenterVertically) { Checkbox(includeSymbols, { includeSymbols = it }); Text("Include symbols") }
                    if (generated.isNotBlank()) {
                        Text(generated, color = Accent)
                        Button(onClick = {
                            val clipboard = context.getSystemService(android.content.Context.CLIPBOARD_SERVICE) as android.content.ClipboardManager
                            clipboard.setPrimaryClip(android.content.ClipData.newPlainText("Generated password", generated))
                            message = "Password copied to clipboard."
                        }) {
                            Text("Copy password")
                        }
                    }
                } },
                confirmButton = { TextButton(onClick = {
                    val chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789" + if (includeSymbols) "!@#$%^&*()-_=+?" else ""
                    generated = buildString { repeat(generatorLength) { append(chars[Random.nextInt(chars.length)]) } }
                }) { Text("Generate") } },
                dismissButton = { TextButton(onClick = { showGenerator = false }) { Text("Close") } })

            if (showSettings && unlocked) AlertDialog(onDismissRequest = { showSettings = false },
                title = { Text("Security & backup") },
                text = { Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text("Automatic lock: immediately when the app leaves the foreground.", color = Muted)
                    Text("Made by Shadowking", color = Accent, fontWeight = FontWeight.SemiBold)
                    if (vault.isBiometricEnabled()) {
                        Text("Fingerprint unlock is enabled.")
                        TextButton(onClick = { vault.disableBiometric(); message = "Fingerprint unlock disabled." }) { Text("Disable fingerprint") }
                    } else {
                        TextButton(onClick = {
                            val manager = BiometricManager.from(context)
                            if (manager.canAuthenticate(BiometricManager.Authenticators.BIOMETRIC_STRONG) != BiometricManager.BIOMETRIC_SUCCESS) {
                                message = "Set up a strong fingerprint in Android settings first."
                            } else try { biometricPrompt(vault.biometricEncryptCipher(), true) }
                            catch (_: Exception) { message = "Could not prepare fingerprint unlock." }
                        }) { Text("Enable fingerprint unlock") }
                    }
                    OutlinedTextField(backupPass, { backupPass = it }, label = { Text("Backup passphrase (10+ characters)") }, visualTransformation = PasswordVisualTransformation(), singleLine = true)
                    Button(onClick = { if (backupPass.length < 10) message = "Use a backup passphrase of at least 10 characters." else { showSettings = false; externalPickerActive = true; createBackup.launch("Lockify-encrypted-backup.lkb") } }, modifier = Modifier.fillMaxWidth()) { Text("Export encrypted backup") }
                    OutlinedButton(onClick = { if (backupPass.length < 10) message = "Enter backup passphrase first." else { showSettings = false; externalPickerActive = true; openBackup.launch(arrayOf("*/*")) } }, modifier = Modifier.fillMaxWidth()) { Text("Import and merge backup") }
                } },
                confirmButton = { TextButton(onClick = { showSettings = false }) { Text("Close") } })

            if (message.isNotBlank() && unlocked) {
                AlertDialog(onDismissRequest = { message = "" }, title = { Text("Lockify") }, text = { Text(message) }, confirmButton = { TextButton(onClick = { message = "" }) { Text("OK") } })
            }
        }
    }
}


@Composable
private fun AnimatedLockifyRobot(modifier: Modifier = Modifier) {
    val motion = rememberInfiniteTransition(label = "lockify-robot")
    val tilt = motion.animateFloat(
        initialValue = -3f,
        targetValue = 3f,
        animationSpec = infiniteRepeatable(
            animation = tween(1800, easing = FastOutSlowInEasing),
            repeatMode = RepeatMode.Reverse
        ),
        label = "robot-tilt"
    )
    val pulse = motion.animateFloat(
        initialValue = 0.97f,
        targetValue = 1.03f,
        animationSpec = infiniteRepeatable(
            animation = tween(1400, easing = FastOutSlowInEasing),
            repeatMode = RepeatMode.Reverse
        ),
        label = "robot-pulse"
    )
    Image(
        painter = painterResource(R.drawable.lockify_robot),
        contentDescription = "Lockify robot mascot",
        contentScale = ContentScale.Fit,
        modifier = modifier.graphicsLayer {
            rotationZ = tilt.value
            scaleX = pulse.value
            scaleY = pulse.value
        }
    )
}
